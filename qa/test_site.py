import os, pathlib, json, math, time
from playwright.sync_api import sync_playwright
BASE=os.environ.get("SITE_URL","http://127.0.0.1:8080").rstrip("/")
OUT=pathlib.Path("qa/current")
OUT.mkdir(parents=True,exist_ok=True)
def check(value,label):
    if not value: raise AssertionError(label)
def loaded(page):
    page.wait_for_function("!document.querySelector('[data-archive][aria-busy=true]')")
    check(page.locator(".archive-status").count()==0,"archive failed")
def layout(page,label):
    check(page.evaluate("document.documentElement.scrollWidth <= innerWidth+1"),label+" document overflow")
    check(page.locator("#site-navigation").count()==1,label+" duplicate/missing header")
    check(page.locator("#lang-toggle").count()==1,label+" language switch")
def target(page,id):
    page.wait_for_function("(id)=>{const e=document.getElementById(id);return e&&Math.abs(scrollY-Math.max(0,Math.min(scrollY+e.getBoundingClientRect().top-document.querySelector('.topbar').getBoundingClientRect().height-20,document.documentElement.scrollHeight-innerHeight)))<4}",arg=id,timeout=6000)
def menu(page,id):
    trigger=page.locator(f'[aria-controls=nav-{id}]')
    if trigger.get_attribute("aria-expanded")!="true":
        trigger.click()
    check(trigger.get_attribute("aria-expanded")=="true",id+" not open")
    check(page.locator(f'#nav-{id}').evaluate("(el)=>!el.inert"),id+" inert")
def run():
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,args=["--no-sandbox"],**({"executable_path":os.environ["SITE_CHROME"]} if os.environ.get("SITE_CHROME") else {}))
        for width in [320,375,768,1024,1440]:
            ctx=browser.new_context(viewport={"width":width,"height":900},has_touch=width<=375,is_mobile=width<=375,device_scale_factor=1)
            page=ctx.new_page()
            errors=[]
            page.on("pageerror",lambda e:errors.append(str(e)))
            page.goto(BASE+"/",wait_until="domcontentloaded")
            loaded(page)
            check(page.locator("script[src*=leaflet]").count()==0,"no map dependency at homepage entry")
            for lang in ["zh","en"]:
                layout(page,f"{width}/{lang}")
                if lang=="en": page.locator("#lang-toggle").click()
                layout(page,f"{width}/{lang}/translated")
                menu(page,"life")
                check(page.locator("#nav-life a").count()==2,"Life destinations")
                page.locator("#nav-life a[href='#music']").click()
                target(page,"music")
                check(page.url.endswith("#music"),"music hash")
                check(page.locator("[aria-controls=nav-life]").get_attribute("aria-expanded")=="false","menu close")
                check(page.locator(".feature-button").count()==2,"two highlights")
                if width>650: check(abs(page.locator(".feature-artwork").nth(0).bounding_box()["height"]-page.locator(".feature-artwork").nth(1).bounding_box()["height"])<2,"aligned feature imagery")
                check(page.locator(".feature-action .feature-arrow").count()==2,"feature arrow retained after translation")
                check("Hamilton" in page.locator(".feature-button").nth(1).inner_text() or "汉密尔顿" in page.locator(".feature-button").nth(1).inner_text(),"Hamilton featured")
                check(page.locator(".album-shelf .shelf-item").count()==6,"six distinct secondary covers")
                check(page.locator(".featured-grid .album-image").count()==3,"three primary covers")
                check(page.evaluate("new Set([...document.querySelectorAll('.featured-works .album-image')].map(i=>i.src)).size===9"),"nine distinct album artworks")
                page.wait_for_function("Array.from(document.querySelectorAll('.featured-grid .album-image')).every(i=>i.complete && i.naturalWidth>0)",timeout=20000)
                if width in [375,1440]:
                    page.locator(".album-shelf").scroll_into_view_if_needed()
                    page.wait_for_function("Array.from(document.querySelectorAll('.album-shelf .album-image')).every(i=>i.complete&&i.naturalWidth>0)",timeout=20000)
                    page.locator(".featured-works").screenshot(path=str(OUT/f"music-full-{width}-{lang}.png"))
                    page.evaluate("window.scrollTo({top:scrollY+document.getElementById('music').getBoundingClientRect().top-document.querySelector('.topbar').getBoundingClientRect().height-20,behavior:'instant'})")
                    page.screenshot(path=str(OUT/f"music-{width}-{lang}.png"))
                page.locator(".feature-button").first.click()
                check(page.locator(".work-dialog").evaluate("el=>el.open"),"modal open")
                check(page.locator(".work-performance").count()==2,"West End records")
                check(page.locator(".stage-recording").count()==2,"both stage recordings retain tracks")
                if width in [375,1440] and lang=="en":page.screenshot(path=str(OUT/f"theatre-detail-{width}.png"))
                page.keyboard.press("Escape")
                check(not page.locator(".work-dialog").evaluate("el=>el.open"),"modal Escape")
                menu(page,"life")
                page.locator("#nav-life a[href='#travel']").click()
                target(page,"travel")
                check(page.locator(".route-controls button").count()==8,"journey controls")
                page.locator(".route-map").scroll_into_view_if_needed()
                page.wait_for_function("document.querySelector('.route-map.leaflet-container')!==null",timeout=15000)
                page.locator(".city-map").scroll_into_view_if_needed()
                page.wait_for_function("document.querySelectorAll('.geo-map.leaflet-container').length===2",timeout=15000)
                page.locator(".route-map").scroll_into_view_if_needed()
                check(page.locator(".geo-map .leaflet-control-attribution").count()==2,"map attribution")
                check(page.locator(".route-map .leaflet-tile").count()>0,"real tile layer")
                check(page.locator(".route-map path.route-arc").count()==19,"all 19 illustrative legs retained")
                check(page.locator(".route-map .overview-label").count()==6,"six overview labels")
                check(page.locator(".route-map path.route-outbound").count()==8,"8 outbound arcs")
                check(page.locator(".route-map path.route-inbound").count()==8,"8 return arcs")
                check(page.locator(".route-map path.route-regional").count()==3,"3 regional arcs")
                check(page.locator(".route-map .route-arrow-marker").count()==16,"16 direction arrows")
                check(page.evaluate("new Set(Array.from(document.querySelectorAll(\x27.route-map path.route-arc\x27),p=>p.getAttribute(\x27d\x27))).size===19"),"each route has distinct geometry")
                if width<=850: page.locator(".route-select").select_option("sg")
                else: page.locator(".route-controls button[data-route=sg]").click()
                page.wait_for_function("selector => document.querySelectorAll(selector).length===4", arg='.route-map path.route-arc[stroke-opacity="0.88"]')
                check(page.locator(".route-map .flight-label").count()==2,"Singapore endpoint labels")
                page.wait_for_function("document.querySelectorAll('.route-map .overview-label').length===0")
                if width in [375,1440] and lang=="en":
                    page.locator(".route-map").screenshot(path=str(OUT/f"flight-singapore-{width}.png"))
                if width<=850: page.locator(".route-select").select_option("")
                else: page.locator(".route-controls button[data-route=\x27\x27]").click()
                page.wait_for_function("document.querySelectorAll('.route-map path.route-arc').length===19")
                page.wait_for_function("document.querySelectorAll('.route-map .flight-label').length===0",timeout=5000)
                check(page.locator(".route-map .overview-label").count()==6,"overview labels restored")
                check(page.locator(".route-map").bounding_box()["height"]>=320,"map visible height")
                check(page.locator(".city-map").bounding_box()["height"]>=280,"city map visible height")
                page.wait_for_function("Array.from(document.querySelectorAll('.route-map img.leaflet-tile')).some(i=>i.complete&&i.naturalWidth>0)",timeout=20000)
                check(page.locator(".uk-count").inner_text().find("33")>=0,"UK count")
                page.locator(".uk-place-select").first.click()
                check(page.locator(".uk-place.is-selected").count()==1,"place selects in same page")
                check(page.locator(".city-map .leaflet-popup").count()==1,"place opens map detail")
                check(page.url.endswith("#travel"),"place selection stays in page")
                if width in [375,1440] and lang=="en":
                    page.locator(".route-map").screenshot(path=str(OUT/f"flight-overview-{width}.png"))
                    page.locator("#travel").scroll_into_view_if_needed()
                    page.screenshot(path=str(OUT/f"travel-{width}.png"))
                if width in [375,1440] and lang=="en":
                    page.locator("#travel-uk").scroll_into_view_if_needed()
                    page.screenshot(path=str(OUT/f"uk-map-{width}.png"))
                menu(page,"work")
                page.locator("#nav-work a[href='#work']").click()
                target(page,"work")
                page.wait_for_function("document.querySelector('#stage-name').textContent==='Vision Router' && !document.querySelector('#stage-visual').classList.contains('is-changing')")
                if width in [375,1440] and lang=="en":page.screenshot(path=str(OUT/f"work-{width}.png"))
            if width==1440:
                page.locator("[aria-controls=nav-life]").hover()
                check(page.locator("[aria-controls=nav-life]").get_attribute("aria-expanded")=="true","desktop hover")
                page.screenshot(path=str(OUT/"desktop-menu.png"))
                page.keyboard.press("Escape")
                check(page.locator("[aria-controls=nav-life]").get_attribute("aria-expanded")=="false","menu Escape")
                # Sample actual intermediate scroll positions, not only final hash.
                page.evaluate("window.scrollTo({top:0,behavior:'instant'})")
                page.evaluate("""()=>{window.__samples=[];const f=()=>{window.__samples.push(scrollY);if(window.__samples.length<70)requestAnimationFrame(f)};requestAnimationFrame(f)}""")
                menu(page,"life")
                page.locator("#nav-life a[href='#travel']").click()
                target(page,"travel")
                check(page.evaluate("new Set(window.__samples.map(y=>Math.round(y))).size>5"),"animated intermediate positions")
                page.go_back()
                target(page,"work")
            for case in ["vision-router","computer-history"]:
                page.goto(BASE+"/projects/"+case+"/",wait_until="domcontentloaded")
                layout(page,f"{width}/{case}")
                menu(page,"life")
                check(page.locator("#nav-life a").count()==2,"case shared nav")
                page.locator("#nav-life a").first.click()
                page.wait_for_url("**/#music")
                loaded(page)
                target(page,"music")
            check(not errors,f"{width} JS errors: {errors}")
            print(f"PASS {width}px: languages, menu, anchors, modal, archive, case round trips",flush=True)
            ctx.close()
        browser.close()
if __name__=="__main__":run()
