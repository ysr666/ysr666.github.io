import os, pathlib
from playwright.sync_api import sync_playwright
BASE=os.environ.get("SITE_URL","http://127.0.0.1:8080").rstrip("/")
OUT=pathlib.Path("qa/current");OUT.mkdir(parents=True,exist_ok=True)
def check(v,label):
    if not v: raise AssertionError(label)
def layout(page):
    check(page.evaluate("document.documentElement.scrollWidth <= innerWidth+1"),"horizontal overflow "+page.url)
    check(page.locator("#site-navigation").count()==1,"shared header")
    check(page.evaluate("""() => {const header=document.querySelector('.topbar-inner'), shell=document.querySelector('.after-work,.project-detail');if(!shell)return true;const edge=e=>e.getBoundingClientRect().left+parseFloat(getComputedStyle(e).paddingLeft);return Math.abs(edge(header)-edge(shell))<=1.5}"""),"shared content rail "+page.url)
def ready(page):
    page.wait_for_function("!document.querySelector('[data-music-view][aria-busy=true],[data-archive][aria-busy=true]')")
    check(page.locator(".archive-status").count()==0,"archive loaded")
def run():
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,args=["--no-sandbox"],**({"executable_path":os.environ["SITE_CHROME"]} if os.environ.get("SITE_CHROME") else {}))
        for width in [320,375,768,1024,1440]:
            ctx=browser.new_context(viewport={"width":width,"height":900},device_scale_factor=1,has_touch=width<=375,is_mobile=width<=375)
            page=ctx.new_page();errors=[];page.on("pageerror",lambda e:errors.append(str(e)))
            page.goto(BASE+"/",wait_until="domcontentloaded");layout(page)
            check(page.locator("[data-archive],[data-music-view]").count()==0,"home does not embed archives")
            check(page.locator("script[src*=leaflet]").count()==0,"home has no maps")
            trigger=page.locator("[aria-controls=nav-life]")
            trigger.focus();page.keyboard.press("Enter")
            check(trigger.get_attribute("aria-expanded")=="true","keyboard opens navigation")
            page.keyboard.press("Tab")
            check(page.evaluate("document.activeElement.closest('#nav-life')!==null"),"Tab enters visible navigation")
            page.keyboard.press("Escape")
            check(trigger.get_attribute("aria-expanded")=="false","Escape closes navigation")
            check(trigger.evaluate("el=>document.activeElement===el"),"Escape restores focus")
            check(page.locator("#nav-life").evaluate("el=>el.inert"),"closed navigation excluded from Tab order")
            check(page.locator(".topnav .nav-trigger,.topnav .nav-direct").evaluate_all("els=>els.every(e=>e.getBoundingClientRect().height>=44&&e.getBoundingClientRect().width>=44)"),"44px navigation targets")
            for lang in ["zh","en"]:
                if lang=="en":page.locator("#lang-toggle").click()
                page.evaluate("document.fonts.ready")
                title=page.locator("#hero-title").bounding_box()
                frame=page.locator(".home-split .visual-frame").bounding_box()
                intro=page.locator(".home-split .intro").bounding_box()
                if width>850:
                    check(abs(title["y"]-frame["y"])<=1.5,"hero title and image frame share top line: "+str((title["y"],frame["y"])))
                    if width>=1440:
                        check(frame["y"]+frame["height"]<=900,"desktop project preview fits first viewport")
                    check(abs(intro["y"]+intro["height"]-frame["y"]-frame["height"])<=1.5,"hero columns share bottom line")
                else:
                    check(abs(title["x"]-frame["x"])<=1.5,"mobile hero gutters align")
                    check(frame["y"]>=intro["y"]+intro["height"]-1,"mobile visual follows intro")
                if width in [375,1024,1440]:
                    page.screenshot(path=str(OUT/f"home-{width}-{lang}.png"))
                page.locator("[aria-controls=nav-life]").click()
                page.locator("#nav-life a[href='/life/music/']").click();page.wait_for_url("**/life/music/");ready(page);layout(page)
                page.wait_for_function("""document.querySelector('#nav-life a[data-nav-destination=music]').getAttribute('aria-current')==='page'""")
                check(page.locator(".record-card").count()==4,"four secondary selected works")
                check(page.locator(".theatre-cover-link").count()==2 and page.locator(".hamilton-cover").count()==1,"three featured works")
                check(page.locator(".music-theme").count()==4,"broad music genres only")
                if width>650:
                    cover_widths=page.locator(".theatre-cover-link .album-cover,.hamilton-cover .album-cover").evaluate_all("els=>els.map(el=>el.getBoundingClientRect().width)")
                    check(max(cover_widths)-min(cover_widths)<=1.5,"equal music cover widths "+str(cover_widths))
                check(page.locator("details").count()==0,"no accordion")
                check(page.locator(".theatre-production").count()==2,"West End experiences")
                check(page.evaluate("document.documentElement.lang.startsWith("+repr(lang)+")"),"language persisted")
                if width in [375,1440]:
                    for card in page.locator(".theatre-cover-link,.hamilton-cover,.record-card").all():card.scroll_into_view_if_needed()
                    page.wait_for_function("Array.from(document.querySelectorAll('[data-music-view] .album-image')).every(i=>i.complete&&i.naturalWidth>0)",timeout=25000)
                    page.locator("[data-music-view]").screenshot(path=str(OUT/f"albums-{width}-{lang}.png"))
                    page.evaluate("window.scrollTo({top:0,behavior:'instant'})")
                    page.screenshot(path=str(OUT/f"music-{width}-{lang}.png"))
                page.locator(".hamilton-cover").click();page.wait_for_url("**/recording/?album=hamilton");ready(page);layout(page)
                check(page.locator(".work-tracks").count()==0,"no imported track history")
                private=page.request.get(BASE+"/life/music.json").json()
                check("catalog" not in private and all(s["id"] in ["musicals","stage"] for s in private["sections"]),"no imported library data in public JSON")
                check(all("tracks" not in r for r in private["featured"]),"no private track lists")
                check(len(private["featured"])==7,"seven reviewed work references, no catalog dump")
                for retired in ["playlist","listening"]:
                    page.goto(BASE+"/life/music/"+retired+"/");page.wait_for_url("**/life/music/");ready(page)
                page.goto(BASE+"/life/travel/");ready(page);layout(page)
                page.locator(".route-map").scroll_into_view_if_needed()
                page.wait_for_function("document.querySelectorAll('.route-map path.route-arc').length===19",timeout=20000)
                check(page.locator(".route-map .overview-label").count()==6,"overview labels")
                if width<=850:page.locator(".route-select").select_option("sg")
                else:page.locator(".route-controls button[data-route=sg]").click()
                page.wait_for_function("selector=>document.querySelectorAll(selector).length===4",arg='.route-map path.route-arc[stroke-opacity="0.88"]')
                if width<=850:page.locator(".route-select").select_option("")
                else:page.locator(".route-controls button[data-route='']").click()
                page.wait_for_function("document.querySelectorAll('.route-map .overview-label').length===6")
                check(page.locator(".impression-card").count()==3,"three editorial impressions")
                check(page.locator(".city-map,.uk-place,.uk-list").count()==0,"no precise itinerary UI")
                travel=page.request.get(BASE+"/life/travel.json").json()
                check("uk" not in travel and "impressions" in travel,"no itinerary source data")
                check(all("points" not in r and "lat" not in r and "lon" not in r for r in travel["impressions"]["items"]),"no location coordinates in editorial excerpts")
                if width in [375,1440] and lang=="zh":
                    page.locator(".travel-impressions").screenshot(path=str(OUT/f"travel-impressions-{width}.png"))
                page.goto(BASE+"/work/#vision");layout(page)
                check(page.locator("main h1").count()==1,"work semantic H1")
                if width<=850:
                    check(not page.locator(".work-split .visual-stage").is_visible(),"compact work page avoids duplicate preview")
                    check(page.locator(".mobile-art").first.is_visible(),"compact case evidence retained")
                if width in [375,1440] and lang=="zh":
                    page.evaluate("window.scrollTo({top:0,behavior:'instant'})");page.screenshot(path=str(OUT/f"work-{width}.png"))
                page.wait_for_function("document.querySelector('#stage-name').textContent==='Vision Router'")
                page.goto(BASE+"/background/");layout(page)
                check(page.locator("#honors").count()==1,"background content")
                if width in [375,1440] and lang=="zh":page.screenshot(path=str(OUT/f"background-{width}.png"))
                page.goto(BASE+"/");layout(page)
            for legacy,dest in [("music","/life/music/"),("travel","/life/travel/"),("vision","/work/#vision"),("honors","/background/#honors")]:
                page.goto(BASE+"/#"+legacy);page.wait_for_url("**"+dest)
            for case in ["vision-router","computer-history"]:
                page.goto(BASE+"/projects/"+case+"/");layout(page)
                check(page.locator("#nav-life a[href='/life/music/']").count()==1,"case navigation")
                if width in [375,1440]:page.screenshot(path=str(OUT/f"case-{case}-{width}.png"))
            check(not errors, str(errors));print(f"PASS {width}px: bilingual pages, editorial selections, travel, privacy checks, compatibility links",flush=True);ctx.close()
        browser.close()
if __name__=="__main__":run()
