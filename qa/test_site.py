import os, pathlib
from playwright.sync_api import sync_playwright
BASE=os.environ.get("SITE_URL","http://127.0.0.1:8080").rstrip("/")
OUT=pathlib.Path("qa/current");OUT.mkdir(parents=True,exist_ok=True)
def check(v,label):
    if not v: raise AssertionError(label)
def layout(page):
    check(page.evaluate("document.documentElement.scrollWidth <= innerWidth+1"),"horizontal overflow "+page.url)
    check(page.locator("#site-navigation").count()==1,"shared header")
def ready(page):
    page.wait_for_function("!document.querySelector('[data-music-view][aria-busy=true],[data-archive][aria-busy=true]')")
    check(page.locator(".archive-status").count()==0,"archive loaded")
def run():
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,args=["--no-sandbox"],**({"executable_path":os.environ["SITE_CHROME"]} if os.environ.get("SITE_CHROME") else {}))
        for width in [320,375,768,1024,1440]:
            ctx=browser.new_context(viewport={"width":width,"height":900},device_scale_factor=1,has_touch=width<=375,is_mobile=width<=375)
            page=ctx.new_page();errors=[];page.on("pageerror",lambda e:errors.append(str(e)))
            page.goto(BASE+"/",wait_until="domcontentloaded");layout(page)
            check(page.locator("[data-archive],[data-music-view]").count()==0,"home does not embed archives")
            check(page.locator("script[src*=leaflet]").count()==0,"home has no maps")
            for lang in ["zh","en"]:
                if lang=="en":page.locator("#lang-toggle").click()
                page.locator("[aria-controls=nav-life]").click()
                page.locator("#nav-life a[href='/life/music/']").click();page.wait_for_url("**/life/music/");ready(page);layout(page)
                check(page.locator(".record-card").count()==22,"22 album cards")
                check(page.locator("details").count()==0,"no accordion")
                check(page.locator(".other-stage-row").count()==3,"remaining watched work records preserved")
                check(page.evaluate("document.documentElement.lang.startsWith("+repr(lang)+")"),"language persisted")
                if width in [375,1440]:
                    for card in page.locator(".record-card").all():card.scroll_into_view_if_needed()
                    page.wait_for_function("Array.from(document.querySelectorAll('.record-card img')).every(i=>i.complete&&i.naturalWidth>0)",timeout=25000)
                    page.locator(".record-grid").screenshot(path=str(OUT/f"albums-{width}-{lang}.png"))
                    page.evaluate("window.scrollTo({top:0,behavior:'instant'})")
                    page.screenshot(path=str(OUT/f"music-{width}-{lang}.png"))
                page.locator(".record-card").first.click();page.wait_for_url("**/recording/?album=hamilton");ready(page);layout(page)
                check(page.locator(".work-tracks li").count()>=4,"Hamilton recorded tracks")
                page.locator(".music-tabs a[href='/life/music/playlist/']").click();page.wait_for_url("**/playlist/");ready(page);layout(page)
                check(page.locator(".catalog-track-group").count()==59,"59 recordings")
                check(page.locator(".catalog-track-group li").count()==78,"78 tracks")
                page.locator(".archive-search").fill("Hamilton")
                check(page.locator(".catalog-track-group:visible").count()==1,"album search")
                page.locator(".music-tabs a[href='/life/music/listening/']").click();page.wait_for_url("**/listening/");ready(page);layout(page)
                check(page.locator(".listening-list").first.locator("li").count()==12,"12 daily tracks")
                check(page.locator(".catalog-stage .listening-list li").count()==2,"two musical favorites preserved")
                page.goto(BASE+"/life/travel/");ready(page);layout(page)
                page.locator(".route-map").scroll_into_view_if_needed()
                page.wait_for_function("document.querySelectorAll('.route-map path.route-arc').length===19",timeout=20000)
                check(page.locator(".route-map .overview-label").count()==6,"overview labels")
                if width<=850:page.locator(".route-select").select_option("sg")
                else:page.locator(".route-controls button[data-route=sg]").click()
                page.wait_for_function("selector=>document.querySelectorAll(selector).length===4",arg='.route-map path.route-arc[stroke-opacity="0.88"]')
                if width<=850:page.locator(".route-select").select_option("")
                else:page.locator(".route-controls button[data-route='']").click()
                page.wait_for_function("document.querySelectorAll('.route-map .overview-label').length===6")
                page.locator(".city-map").scroll_into_view_if_needed()
                page.wait_for_function("document.querySelector('.city-map.leaflet-container')!==null",timeout=20000)
                page.locator(".uk-place-select").first.click()
                check(page.locator(".city-map .leaflet-popup").count()==1,"city place selection")
                page.goto(BASE+"/work/#vision");layout(page)
                page.wait_for_function("document.querySelector('#stage-name').textContent==='Vision Router'")
                page.goto(BASE+"/background/");layout(page)
                check(page.locator("#honors").count()==1,"background content")
                page.goto(BASE+"/");layout(page)
            for legacy,dest in [("music","/life/music/"),("travel","/life/travel/"),("vision","/work/#vision"),("honors","/background/#honors")]:
                page.goto(BASE+"/#"+legacy);page.wait_for_url("**"+dest)
            for case in ["vision-router","computer-history"]:
                page.goto(BASE+"/projects/"+case+"/");layout(page)
                check(page.locator("#nav-life a[href='/life/music/']").count()==1,"case navigation")
            check(not errors, str(errors));print(f"PASS {width}px: bilingual pages, albums, track index, travel, compatibility links",flush=True);ctx.close()
        browser.close()
if __name__=="__main__":run()
